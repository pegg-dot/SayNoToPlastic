import fs from "node:fs";
import crypto from "node:crypto";
let passed=0, failed=0;
const expect=(c,m)=>{ if(c){console.log(`[PASS] ${m}`);passed++;} else {console.error(`[FAIL] ${m}`);failed++;} };
const scene=fs.readFileSync("app/components/AnatomyScene.tsx","utf8");
const build=fs.readFileSync("app/build-version.ts","utf8");
expect(build.includes("v40.32-microplastic-renderer-repair"),"Build records v40.32 renderer repair.");
expect(scene.includes("useLayoutEffect"),"Particle instance colors initialize before paint.");
expect(scene.includes("setColorAt(index, color.set(point.tint))"),"Live instances receive their configured tint.");
expect(scene.includes("material.current.needsUpdate = true"),"Material recompiles after instanceColor creation.");
const materialBlock=scene.slice(scene.indexOf("<meshBasicMaterial"), scene.indexOf("</instancedMesh>", scene.indexOf("<meshBasicMaterial")));
expect(!materialBlock.includes("vertexColors"),"Microplastic material does not enable missing geometry vertex colors.");
expect(materialBlock.includes("toneMapped={false}"),"Particle colors bypass anatomy tone mapping.");
for(const shape of ["shard","flake","chip","fiber","bead","film","grain"]) expect(scene.includes(`shape: "${shape}"`),`${shape} population remains live.`);
for(const color of ["#197fd1","#ff7b28","#ffd34d","#67c95f","#ff77ac","#9a6cff"]) expect(scene.includes(color),`${color} remains in live palettes.`);
expect(scene.includes("size = 0.0034 + n(4) * 0.0135"),"Main fragments use reduced microplastic-scale sizing.");
expect(scene.includes("size = 0.0018 + n(4) * 0.0048"),"Grains retain a smaller size family.");
expect(scene.includes('layers: layerState({ body: 0.05, testes: 1, particles: 0.24 })'),"Testicular tissue remains final with particles enabled.");
const lock=crypto.createHash("sha256").update(fs.readFileSync("package-lock.json")).digest("hex");
expect(lock==="7915a420ef99c285f0a152256b2ca9742f3b520834be90ab937935af8225e85e","Package lock unchanged.");
console.log(`[SUMMARY] ${passed} passed, ${failed} failed.`); process.exit(failed?1:0);
